#!/bin/bash
# V1 release execution (2026-11-03, corrected 2026-11-07). The exact, exception-safe execution
# mechanism for pushing ONLY the engineering candidate set -- never the gated/independent
# migrations that also happen to be pending, and never the separate Daily content-ops files.
#
# CORRECTED (2026-11-07), item 1: an independent inspection found this script hardcoded its
# own copy of the excluded-files list AND a stale "exactly 21" count -- both had drifted the
# moment a 22nd engineering migration was added, because nothing forced this script and
# scripts/verify-migration-allowlist.ts to agree. Neither hardcodes anything any more: both
# read supabase/release-manifest.json, generated by scripts/generate-migration-manifest.ts,
# which also records a sha256 of each file's exact content -- this script verifies every
# manifest-listed file still matches that hash before doing anything else, and verifies the
# dry-run's resulting pending set is EXACTLY (not just a matching count of) the manifest's
# engineering candidate set filenames, in order.
#
# `supabase db push` has no per-file selection flag (confirmed: `supabase db push --help`
# offers only --include-all/--dry-run, nothing scoped to specific files) -- the only real,
# CLI-enforced restriction is physically removing the other files from supabase/migrations/
# before running it, exactly like the already-proven pattern for the destructive reset
# (supabase/manual_operations/). This script does that move, runs the push, and restores the
# excluded files in a `trap` on EXIT/INT/TERM/HUP -- confirmed by an actual kill -TERM test, not
# assumed, including the one real limitation that test surfaced: restoration is NOT necessarily
# INSTANT -- if the signal arrives while a slow foreground network call (the dry-run or the
# real push itself) is in flight, bash defers running the trap until that call returns control
# to the shell (standard, unavoidable POSIX behavior, not a bug here). The files are still
# guaranteed to be restored the moment the script's own process exits for any reason it is
# possible to trap. The one signal NO shell trap can ever catch is SIGKILL (-9) -- if this
# script is killed with -9 specifically, check supabase/migrations/ by hand afterward and
# restore any files still sitting in the printed holdout directory before doing anything else.
#
# This script does NOT run automatically and is NOT invoked by anything else. It requires
# explicit owner authorization before each real run. Defaults to --dry-run; pass --apply (and
# only after that authorization) to actually push the engineering candidate set.
# Pass --apply-daily-content after a successful engineering push (separately authorized) to
# apply the 5 staged Daily content operations, in their tested manifest order, against
# supabase/pending-owner-review/ -- these are data-ops, never schema migrations, and
# `supabase db push` never sees them; they are applied directly via `psql`/the Supabase SQL
# connection this environment is already configured to reach.
#
# Usage: ./scripts/safe-migration-push.sh [--apply | --apply-daily-content]

set -euo pipefail
cd "$(dirname "$0")/.."

command -v jq >/dev/null 2>&1 || { echo "ERROR: jq is required (brew install jq) -- this script reads supabase/release-manifest.json with it, never by hand-parsing JSON in bash." >&2; exit 1; }

MANIFEST="supabase/release-manifest.json"
[ -f "$MANIFEST" ] || { echo "ERROR: $MANIFEST not found. Run scripts/generate-migration-manifest.ts first." >&2; exit 1; }

MODE="dry-run"
case "${1:-}" in
  --apply) MODE="apply" ;;
  --apply-daily-content) MODE="apply-daily-content" ;;
  "") MODE="dry-run" ;;
  *) echo "ERROR: unknown argument '${1:-}'. Usage: $0 [--apply | --apply-daily-content]" >&2; exit 1 ;;
esac

EXPECTED_PROJECT_REF="$(jq -r '.expectedProjectRef' "$MANIFEST")"
LAST_REHEARSED_COMMIT="$(jq -r '.lastRehearsedCommit // "null"' "$MANIFEST")"
# read_lines_into: portable substitute for bash4+'s `mapfile` -- macOS ships bash 3.2, which
# does not have it. Populates the named array (nameref via eval, since bash 3.2 also lacks
# `declare -n`) with one element per line of the given command's output.
read_lines_into() {
  local __varname="$1"; shift
  local __line __i=0
  eval "$__varname=()"
  while IFS= read -r __line; do
    eval "$__varname[$__i]=\$__line"
    __i=$((__i + 1))
  done
  unset __line __i
}

read_lines_into ENGINEERING_FILES < <(jq -r '.buckets.engineeringCandidateSet[].file' "$MANIFEST")
read_lines_into GATED_FILES < <(jq -r '.buckets.explicitlyGated[].file' "$MANIFEST")
read_lines_into INDEPENDENT_FILES < <(jq -r '.buckets.independentReady[].file' "$MANIFEST")
read_lines_into DAILY_CONTENT_FILES < <(jq -r '.buckets.dailyContentOperations[].file' "$MANIFEST")
EXCLUDED_FILES=("${GATED_FILES[@]}" "${INDEPENDENT_FILES[@]}")

echo "=== 1. Content integrity: verifying every manifest-listed migration file's hash ==="
HASH_FAILED=0
check_hash() {
  local dir="$1" file="$2" expected="$3" actual
  if [ ! -f "$dir/$file" ]; then
    echo "  MISSING: $dir/$file (in manifest, not on disk)" >&2
    HASH_FAILED=1
    return
  fi
  actual="$(shasum -a 256 "$dir/$file" | cut -d' ' -f1)"
  if [ "$actual" != "$expected" ]; then
    echo "  CHANGED: $dir/$file -- content does not match the manifest's recorded hash. Re-run scripts/generate-migration-manifest.ts (after re-rehearsing) if this change is intentional; otherwise investigate before proceeding." >&2
    HASH_FAILED=1
  fi
}
while IFS=$'\t' read -r file hash; do check_hash "supabase/migrations" "$file" "$hash"; done < <(jq -r '.buckets.engineeringCandidateSet[] | "\(.file)\t\(.sha256)"' "$MANIFEST")
while IFS=$'\t' read -r file hash; do check_hash "supabase/migrations" "$file" "$hash"; done < <(jq -r '.buckets.explicitlyGated[] | "\(.file)\t\(.sha256)"' "$MANIFEST")
while IFS=$'\t' read -r file hash; do check_hash "supabase/migrations" "$file" "$hash"; done < <(jq -r '.buckets.independentReady[] | "\(.file)\t\(.sha256)"' "$MANIFEST")
while IFS=$'\t' read -r file hash; do check_hash "supabase/pending-owner-review" "$file" "$hash"; done < <(jq -r '.buckets.dailyContentOperations[] | "\(.file)\t\(.sha256)"' "$MANIFEST")
if [ "$HASH_FAILED" -ne 0 ]; then
  echo "ERROR: one or more files failed content verification above. Aborting before touching anything." >&2
  exit 1
fi
echo "Confirmed: all ${#ENGINEERING_FILES[@]} engineering + ${#GATED_FILES[@]} gated + ${#INDEPENDENT_FILES[@]} independent + ${#DAILY_CONTENT_FILES[@]} Daily content-ops files match the manifest exactly."

echo ""
echo "=== 2. Target project verification ==="
# \`supabase status\` inspects local Docker and fails on Macs without Docker.
# Use the authenticated, read-only remote project listing instead, and require
# exactly one linked project before comparing its ref to the release manifest.
if ! PROJECTS_JSON="$(npx supabase projects list --output json 2>&1)"; then
  echo "ERROR: could not list authenticated Supabase projects. Aborting." >&2
  exit 1
fi
if ! LINKED_REF="$(printf '%s' "$PROJECTS_JSON" | jq -er '[.[] | select(.linked == true) | .ref] | if length == 1 and (.[0] | type == "string") then .[0] else empty end')"; then
  echo "ERROR: could not determine exactly one linked project from the authenticated project listing. Aborting." >&2
  exit 1
fi
if [ ! -f supabase/.temp/project-ref ]; then
  echo "ERROR: local Supabase project link is missing. Aborting." >&2
  exit 1
fi
LOCAL_LINKED_REF="$(tr -d '[:space:]' < supabase/.temp/project-ref)"
if [ "$LOCAL_LINKED_REF" != "$LINKED_REF" ]; then
  echo "ERROR: local link ($LOCAL_LINKED_REF) differs from the remote-linked project ($LINKED_REF). Aborting." >&2
  exit 1
fi
if [ "$LINKED_REF" != "$EXPECTED_PROJECT_REF" ]; then
  echo "ERROR: linked project ref ($LINKED_REF) does NOT match the manifest's expectedProjectRef ($EXPECTED_PROJECT_REF). Refusing to proceed -- this would push against the wrong project." >&2
  exit 1
fi
echo "Confirmed: linked project ref ($LINKED_REF) matches the manifest's expectedProjectRef."

echo ""
echo "=== 3. Release commit verification ==="
CURRENT_COMMIT="$(git rev-parse HEAD)"
if [ "$LAST_REHEARSED_COMMIT" = "null" ]; then
  echo "WARNING: the manifest has no lastRehearsedCommit recorded -- this content's hash has never been marked as rehearsed. Proceed only if you know why." >&2
elif [ "$CURRENT_COMMIT" = "$LAST_REHEARSED_COMMIT" ]; then
  echo "Confirmed: working tree HEAD ($CURRENT_COMMIT) matches the manifest's lastRehearsedCommit exactly."
else
  echo "NOTE: working tree HEAD ($CURRENT_COMMIT) differs from lastRehearsedCommit ($LAST_REHEARSED_COMMIT). The content-hash checks above are the hard gate -- if every hash passed, the actual migration/content-ops bytes are unchanged since that rehearsal regardless of what else moved in the tree."
fi

HOLDOUT_DIR="$(mktemp -d /tmp/migration-safety-holdout.XXXXXX)"
RESTORED=0
restore_excluded_files() {
  local status=$?
  if [ "$RESTORED" -eq 1 ]; then exit "$status"; fi
  RESTORED=1
  echo ""
  echo "Restoring the ${#EXCLUDED_FILES[@]} temporarily-excluded migration files to supabase/migrations/ ..."
  for f in "${EXCLUDED_FILES[@]}"; do
    if [ -f "$HOLDOUT_DIR/$f" ]; then
      mv "$HOLDOUT_DIR/$f" "supabase/migrations/$f"
      echo "  restored: $f"
    fi
  done
  rmdir "$HOLDOUT_DIR" 2>/dev/null || true
  if [ "$status" -ne 0 ]; then
    echo "" >&2
    echo "safe-migration-push.sh exited with status $status -- the excluded files were restored regardless, nothing was left missing from the working tree." >&2
    echo "If this happened DURING an --apply push (not the dry-run check before it), the remote migration history may now be PARTIAL." >&2
    echo "DO NOT RE-RUN THIS SCRIPT until you reconcile remote state first:" >&2
    echo "  npx supabase migration list --remote" >&2
    echo "Compare that output against the engineering candidate set in $MANIFEST by hand, confirm exactly which of the 22 files actually applied remotely, and only then decide whether to retry (which will attempt to apply the remaining ones) or roll back." >&2
  fi
  exit "$status"
}
# Trap EXIT (covers normal completion, `exit N`, and most error paths under `set -e`) AND
# INT/TERM/HUP explicitly. CONFIRMED BY A REAL TEST, not assumed: `trap ... EXIT` alone did NOT
# fire when this script was SIGTERM'd while a foreground child (npx) was running -- the shell
# was killed outright, the holdout files were left genuinely missing from supabase/migrations/.
# Explicitly trapping the signals too (and having that handler call the exact same cleanup,
# then exit) is the standard, documented fix for this exact bash gotcha.
trap restore_excluded_files EXIT INT TERM HUP

if [ "$MODE" = "apply-daily-content" ]; then
  echo ""
  echo "=== Applying the ${#DAILY_CONTENT_FILES[@]} Daily content operations, in manifest order ==="
  echo "These are NOT schema migrations and are never touched by \`supabase db push\` -- requires its own, separate owner authorization from the engineering migration push above."
  for f in "${DAILY_CONTENT_FILES[@]}"; do
    echo "  -> $f"
    npx supabase db query --remote --file "supabase/pending-owner-review/$f" || {
      echo "ERROR: $f failed to apply. STOP -- do not apply the remaining content-ops files until you have confirmed exactly what state $f left the database in." >&2
      exit 1
    }
  done
  echo "All ${#DAILY_CONTENT_FILES[@]} Daily content operations applied successfully."
  exit 0
fi

echo ""
echo "=== 4. Moving ${#EXCLUDED_FILES[@]} gated/independent migrations out of supabase/migrations/ (to $HOLDOUT_DIR) ==="
for f in "${EXCLUDED_FILES[@]}"; do
  if [ ! -f "supabase/migrations/$f" ]; then
    echo "ERROR: expected file not found: supabase/migrations/$f -- aborting before moving anything else." >&2
    exit 1
  fi
done
for f in "${EXCLUDED_FILES[@]}"; do
  mv "supabase/migrations/$f" "$HOLDOUT_DIR/$f"
done

echo ""
echo "=== 5. Verifying the real linked-project dry-run shows EXACTLY the engineering candidate set ==="
DRYRUN_OUTPUT="$(npx supabase db push --remote --dry-run 2>&1)"
read_lines_into PENDING_FILES < <(echo "$DRYRUN_OUTPUT" | grep -oE '•\s+\S+\.sql' | awk '{print $2}')
echo "Would push (${#PENDING_FILES[@]}):"
printf '  %s\n' "${PENDING_FILES[@]}"

if [ "${#PENDING_FILES[@]}" -ne "${#ENGINEERING_FILES[@]}" ]; then
  echo "ERROR: expected exactly ${#ENGINEERING_FILES[@]} pending migrations, found ${#PENDING_FILES[@]}. Aborting -- not pushing anything." >&2
  exit 1
fi
for i in "${!ENGINEERING_FILES[@]}"; do
  if [ "${PENDING_FILES[$i]:-}" != "${ENGINEERING_FILES[$i]}" ]; then
    echo "ERROR: pending migration #$((i+1)) is '${PENDING_FILES[$i]:-<missing>}', expected '${ENGINEERING_FILES[$i]}' -- exact filename/order mismatch against the manifest. Aborting -- not pushing anything." >&2
    exit 1
  fi
done
echo "Confirmed: the pending set is EXACTLY the ${#ENGINEERING_FILES[@]}-file engineering candidate set, in the manifest's exact order."

if [ "$MODE" = "dry-run" ]; then
  echo ""
  echo "DRY RUN ONLY (default). Re-run with --apply, after explicit owner authorization, to actually push."
  exit 0
fi

echo ""
echo "=== APPLYING: supabase db push --remote --yes ==="
echo "(the gated/independent files are physically absent, so this can only apply the verified ${#ENGINEERING_FILES[@]}-file engineering candidate set)"
# --yes: the CLI refuses to mutate a hosted project non-interactively without it
# (HostedMutationConsentRequiredError) -- its own built-in safety gate for exactly this kind
# of automated run. Only ever pass --apply to THIS script after real, explicit owner
# authorization of the apply itself; --yes here is not a separate decision, it is what lets
# that already-given authorization actually execute non-interactively.
if ! npx supabase db push --remote --yes; then
  echo "" >&2
  echo "ERROR: supabase db push failed or was interrupted mid-apply. STOP." >&2
  echo "Do not retry automatically. Run \`npx supabase migration list --remote\` to see exactly which of the ${#ENGINEERING_FILES[@]} migrations actually applied remotely before deciding what to do next." >&2
  exit 1
fi
echo "Push complete -- all ${#ENGINEERING_FILES[@]} engineering candidate migrations applied."
echo "The 5 Daily content operations are a SEPARATE, later step -- re-run this script with --apply-daily-content, under its own owner authorization, once this push is confirmed healthy."
