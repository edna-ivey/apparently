// Build 22 migration safety gate. Runs the real, read-only `supabase db push --remote
// --dry-run` (never applies anything) and categorizes every migration it would push into
// exactly one of three explicit buckets -- it never says "the pending set is safe to push,"
// only ever "here is what it contains and which bucket each one falls into."
//
// CORRECTED (V1 release execution, 2026-11-07), item 1: no longer hardcodes its own copy of
// the bucket lists -- an independent inspection found scripts/safe-migration-push.sh carried a
// SEPARATE hardcoded list (and a stale file count) that had drifted the moment a 22nd
// engineering migration was added, because nothing forced the two scripts to agree. Both now
// read supabase/release-manifest.json, the one authoritative, version-controlled manifest
// (generated by scripts/generate-migration-manifest.ts). This script additionally verifies
// each listed file's CONTENT against the manifest's recorded sha256 -- a file that kept its
// name and position but changed content (not just a missing/extra/renamed file) is caught
// here, which a filename-or-count-only check cannot do.
//
// Run with: npx tsx scripts/verify-migration-allowlist.ts

declare const process: { exit: (code: number) => void };
declare const require: (id: string) => any;
declare const __dirname: string;
const { execSync } = require('child_process');
const { readFileSync, existsSync } = require('fs');
const { createHash } = require('crypto') as unknown as { createHash: (algo: string) => { update: (d: string) => any; digest: (enc: string) => string } };
const { join } = require('path') as unknown as { join: (...parts: string[]) => string };

const REPO_ROOT = join(__dirname, '..');
const sha256 = (text: string): string => createHash('sha256').update(text).digest('hex');

type ManifestEntry = { file: string; sha256: string };
type Manifest = {
  expectedProjectRef: string;
  lastRehearsedCommit: string | null;
  buckets: {
    engineeringCandidateSet: ManifestEntry[];
    independentReady: ManifestEntry[];
    explicitlyGated: ManifestEntry[];
    dailyContentOperations: ManifestEntry[];
  };
};

const manifestPath = join(REPO_ROOT, 'supabase/release-manifest.json');
if (!existsSync(manifestPath)) {
  console.error(`FAIL: ${manifestPath} not found. Run scripts/generate-migration-manifest.ts first -- there is no other source of truth this script will fall back to.`);
  process.exit(1);
}
const manifest: Manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));

let failures = 0;
const assert = (condition: unknown, message: string): void => {
  if (!condition) {
    failures += 1;
    console.error(`FAIL: ${message}`);
  } else {
    console.log(`OK: ${message}`);
  }
};

// --- 1. Content integrity: every manifest-listed file (migrations AND content-ops) must
//     exist and match its recorded hash exactly. Order within a bucket is the manifest's own
//     array order (chronological filename order is enforced at generation time).
const BUCKET_DIRS: Record<keyof Manifest['buckets'], string> = {
  engineeringCandidateSet: 'supabase/migrations',
  independentReady: 'supabase/migrations',
  explicitlyGated: 'supabase/migrations',
  dailyContentOperations: 'supabase/pending-owner-review',
};

for (const [bucketName, entries] of Object.entries(manifest.buckets) as [keyof Manifest['buckets'], ManifestEntry[]][]) {
  const dir = BUCKET_DIRS[bucketName];
  for (const entry of entries) {
    const path = join(REPO_ROOT, dir, entry.file);
    if (!existsSync(path)) {
      failures += 1;
      console.error(`FAIL: [${bucketName}] ${entry.file} is in the manifest but does not exist at ${dir}/`);
      continue;
    }
    const actualHash = sha256(readFileSync(path, 'utf8'));
    assert(actualHash === entry.sha256, `[${bucketName}] ${entry.file} content matches the manifest's recorded hash`);
  }
}

const orderCheck = (entries: ManifestEntry[]): boolean => {
  const names = entries.map((e) => e.file);
  return JSON.stringify([...names].sort()) === JSON.stringify(names);
};
assert(orderCheck(manifest.buckets.engineeringCandidateSet), 'engineeringCandidateSet is in chronological (lexicographic filename) order -- Supabase migration history and `supabase db push` both depend on this');
assert(orderCheck(manifest.buckets.dailyContentOperations), 'dailyContentOperations is in chronological (lexicographic filename) order');

// --- 2. Informational: has this exact, hash-verified content actually been rehearsed?
const currentCommit = execSync('git rev-parse HEAD', { encoding: 'utf8', cwd: REPO_ROOT }).trim();
if (!manifest.lastRehearsedCommit) {
  console.log('NOTE: lastRehearsedCommit is not set in the manifest -- this content has never been marked as rehearsed. Treat as unverified.');
} else if (manifest.lastRehearsedCommit === currentCommit) {
  console.log(`OK: working tree HEAD (${currentCommit.slice(0, 12)}) matches the manifest's lastRehearsedCommit exactly.`);
} else {
  console.log(`NOTE: working tree HEAD (${currentCommit.slice(0, 12)}) differs from the manifest's lastRehearsedCommit (${manifest.lastRehearsedCommit.slice(0, 12)}). The sha256 hashes above are still the hard gate -- if every file's content still matches, the actual migration/content-ops bytes are unchanged since that rehearsal regardless of what else moved in the tree. If any hash FAILED above, re-rehearse before trusting this manifest.`);
}

// --- 3. Target project verification (which Supabase project is actually linked).
let linkedProjectRef: string | null = null;
try {
  // `supabase status` exits non-zero when local Docker/Podman isn't running, but still PRINTS
  // the linked project ref in its JSON error payload before that failure -- confirmed
  // directly, not assumed: {"linked_project":{"project_ref":"...","project_name":"...",...},
  // "_tag":"Error","error":{"code":"StatusDbInspectError",...}}. execSync throws on a non-zero
  // exit, so stdout/stderr are read from the thrown error's own fields, not the try block's
  // normal return value.
  execSync('npx supabase status 2>&1', { encoding: 'utf8', cwd: REPO_ROOT });
} catch (e: unknown) {
  const err = e as { stdout?: string; stderr?: string };
  const combined = `${err.stdout ?? ''}${err.stderr ?? ''}`;
  const jsonMatch = combined.match(/\{"linked_project":\{"project_ref":"([a-z0-9]+)"/);
  const plainMatch = combined.match(/API URL[^\n]*https:\/\/([a-z0-9]+)\.supabase\.co/i);
  if (jsonMatch) linkedProjectRef = jsonMatch[1];
  else if (plainMatch) linkedProjectRef = plainMatch[1];
}
if (!linkedProjectRef) {
  try {
    const listOutput = execSync('npx supabase projects list 2>&1', { encoding: 'utf8', cwd: REPO_ROOT });
    const linkedLine = listOutput.split('\n').find((l: string) => l.includes('●') || /linked/i.test(l));
    const refMatch = linkedLine?.match(/([a-z0-9]{20})/);
    if (refMatch) linkedProjectRef = refMatch[1];
  } catch {
    // fall through
  }
}
if (!linkedProjectRef) {
  console.log('NOTE: could not determine the currently linked Supabase project ref from `supabase status` or `supabase projects list` output -- verify manually before any push that the linked project matches expectedProjectRef in the manifest.');
} else {
  assert(linkedProjectRef === manifest.expectedProjectRef, `linked Supabase project ref (${linkedProjectRef}) matches the manifest's expectedProjectRef (${manifest.expectedProjectRef})`);
}

if (failures > 0) {
  console.error(`\n${failures} check(s) FAILED. Do not push anything.`);
  process.exit(1);
}

// --- 4. Dry-run categorization (existing behavior, now sourced from the manifest).
console.log('\nRunning read-only `supabase db push --remote --dry-run` (applies nothing)...');
const output = execSync('npx supabase db push --remote --dry-run 2>&1', { encoding: 'utf8', cwd: REPO_ROOT });

const bulletMatches = [...output.matchAll(/•\s+(\S+\.sql)/g)].map((m: RegExpMatchArray) => m[1]);
if (bulletMatches.length === 0 && !/up to date/i.test(output)) {
  console.error('FAIL: could not find the bulleted migration list in `supabase db push --dry-run` output, and the output does not say the project is up to date either -- CLI output format may have changed again. Raw output:');
  console.error(output);
  process.exit(1);
}
const wouldPush = new Set<string>(bulletMatches);

const jsonLine = output.trim().split('\n').find((line: string) => line.trim().startsWith('{"'));
if (jsonLine) {
  try {
    const parsed = JSON.parse(jsonLine) as { migrations: string[] };
    const jsonSet = new Set(parsed.migrations);
    const disagreement = [...wouldPush].filter((m) => !jsonSet.has(m)).concat([...jsonSet].filter((m) => !wouldPush.has(m)));
    if (disagreement.length > 0) {
      console.error(`FAIL: the bulleted list and the JSON summary line disagree on: ${JSON.stringify(disagreement)} -- treating this as a parse problem, not picking one arbitrarily.`);
      process.exit(1);
    }
    console.log('(optional cross-check: JSON summary line present and agrees with the bulleted list)');
  } catch {
    console.log('(optional cross-check: a line starting with \'{"\' was present but did not parse as the expected JSON shape -- ignored, the bulleted list is authoritative)');
  }
} else {
  console.log('(optional cross-check: this CLI version does not print the JSON summary line -- expected on some installs, not required)');
}

const engineeringNames = manifest.buckets.engineeringCandidateSet.map((e) => e.file);
const independentNames = manifest.buckets.independentReady.map((e) => e.file);
const gatedNames = manifest.buckets.explicitlyGated.map((e) => e.file);
const allKnown = new Set([...engineeringNames, ...independentNames, ...gatedNames]);

const unknown = [...wouldPush].filter((m) => !allKnown.has(m));
assert(unknown.length === 0, `no UNKNOWN migration would be pushed (found: ${JSON.stringify(unknown)}) -- anything pending must be one of the manifest's three migration buckets`);

const gatedButPending = gatedNames.filter((m) => wouldPush.has(m));
const candidatePending = engineeringNames.filter((m) => wouldPush.has(m));
const independentPending = independentNames.filter((m) => wouldPush.has(m));

console.log('\n=== Categorized result -- this is a report, never a statement of owner/production approval ===');
console.log(`ENGINEERING CANDIDATE SET for this body of work -- NOT owner-authorized, requires explicit separate sign-off before any push (${candidatePending.length}/${engineeringNames.length} pending): ${JSON.stringify(candidatePending)}`);
console.log(`EXPLICITLY GATED, must NOT be applied with this deployment (${gatedButPending.length} pending): ${JSON.stringify(gatedButPending)}`);
console.log(`INDEPENDENT, unrelated, awaiting their own separate sign-off (${independentPending.length} pending): ${JSON.stringify(independentPending)}`);
console.log(`DAILY CONTENT OPERATIONS (not schema migrations, never seen by \`supabase db push\` -- applied separately, in manifest order, after the engineering candidate set): ${JSON.stringify(manifest.buckets.dailyContentOperations.map((e) => e.file))}`);

if (gatedButPending.length !== gatedNames.length) {
  console.log(`NOTE: ${gatedNames.length - gatedButPending.length} gated migration(s) are not currently pending (already applied, or removed) -- re-verify the manifest's explicitlyGated bucket is still accurate.`);
}

if (failures > 0) {
  console.error(`\n${failures} check(s) FAILED. Do not push anything.`);
  process.exit(1);
}

console.log(
  '\nALL checks PASSED: every currently-pending migration is accounted for in one of the three explicit buckets, every manifest-listed file\'s content is unchanged since it was last verified, and the linked project matches expectation. ' +
  'This is an ENGINEERING CANDIDATE SET, not owner or production approval -- it does not authorize pushing anything. ' +
  'If and when the owner separately approves a push, apply ONLY the candidate list above, in that exact chronological ' +
  'order, never an unrestricted `supabase db push`. The GATED and INDEPENDENT migrations require their own separate, ' +
  'later owner review before they are ever applied.',
);
