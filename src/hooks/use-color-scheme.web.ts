import { useEffect, useState } from 'react';
import { useColorScheme as useRNColorScheme } from 'react-native';

/**
 * To support static rendering, this value needs to be re-calculated on the client side for web
 */
export function useColorScheme() {
  const [hasHydrated, setHasHydrated] = useState(false);

  useEffect(() => {
    // Detecting "the client has mounted/hydrated" is impossible to know during the render
    // itself (by definition, the first client render must match the server-rendered markup) --
    // this is the standard Expo Router web template pattern for static rendering, and has no
    // render-time equivalent. Scoped to this one line.
    // eslint-disable-next-line react-hooks/set-state-in-effect
    setHasHydrated(true);
  }, []);

  const colorScheme = useRNColorScheme();

  if (hasHydrated) {
    return colorScheme;
  }

  return 'light';
}
